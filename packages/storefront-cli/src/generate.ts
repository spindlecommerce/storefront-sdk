import type { ComponentDefinition, FieldDefinition } from "./definitions.ts";

const pascal = (code: string) =>
  code
    .split(/[_-]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");

const quote = (value: string) => JSON.stringify(value);

const fieldType = (field: FieldDefinition, nodeType: (code: string) => string, all: ComponentDefinition[]): string => {
  switch (field.type) {
    case "text":
    case "richText":
    case "color":
    case "date":
      return "string | null";
    case "number":
      return "number | null";
    case "boolean":
      return "boolean";
    case "select":
      return `${(field.options ?? []).map((o) => quote(o.value)).join(" | ") || "string"} | null`;
    case "image":
      return "BuilderImage | null";
    case "link":
      return "BuilderLink | null";
    case "product":
    case "category":
      return "string | null";
    case "products":
      return "string[]";
    case "blocks": {
      const allowed = field.allowedComponents?.length ? field.allowedComponents : all.filter((c) => c.kind === "component").map((c) => c.code);
      return `Array<${allowed.map(nodeType).join(" | ") || "never"}>`;
    }
    case "list":
      return `Array<BuilderItem<{ ${(field.fields ?? []).map((f) => `${f.key}: ${fieldType(f, nodeType, all)}`).join("; ")} }>>`;
  }
};

/** Types for content as the Storefront API delivers it: one locale, references as global ids. */
export const generateTypes = (definitions: ComponentDefinition[]) => {
  const nodeType = (code: string) => `${pascal(code)}Node`;
  const lines = [
    "// Generated by `spindle-storefront components types`; regenerate after changing components.",
    "// Content as the Storefront API delivers it: text in the request locale, links with hrefs,",
    "// products and categories as global ids (resolve them through Page.references).",
    "",
    "export type BuilderImage = { url: string; alt: string | null; width: number | null; height: number | null };",
    'export type BuilderLink = { kind: "url" | "page" | "product" | "category"; href: string | null; id: string | null; newTab: boolean };',
    "export type BuilderItem<F> = { id: string; fields: F };",
    "export type BuilderNode<C extends string, F, V extends string | null = null> = { id: string; component: C; variation: V; fields: F };",
    "",
  ];
  for (const def of [...definitions].sort((a, b) => a.code.localeCompare(b.code))) {
    const variations = def.variations.length ? def.variations.map((v) => quote(v.code)).join(" | ") : "null";
    const binding = def.templateFor
      ? def.kind === "content_type"
        ? ` A template for ${def.templateFor} pages.`
        : ` Shows ${def.templateFor} data, so only in ${def.templateFor} templates and sections.`
      : def.sectionsFor
        ? ` Belongs to one ${def.sectionsFor}: render it where the ${def.sectionsFor}'s template places its sections.`
        : "";
    lines.push(`/** ${def.name}${def.description ? `: ${def.description}` : ""}${binding} */`);
    if (def.fields.length) {
      lines.push(`export type ${pascal(def.code)}Fields = {`);
      for (const field of def.fields) {
        const optional = field.variations?.length ? "?" : "";
        const doc = [field.label, field.description, field.variations?.length ? `Only for ${field.variations.join(", ")}.` : ""].filter(Boolean).join(". ");
        lines.push(`  /** ${doc} */`);
        lines.push(`  ${field.key}${optional}: ${fieldType(field, nodeType, definitions)};`);
      }
      lines.push("};");
    } else lines.push(`export type ${pascal(def.code)}Fields = Record<string, never>;`);
    lines.push(`export type ${nodeType(def.code)} = BuilderNode<${quote(def.code)}, ${pascal(def.code)}Fields, ${variations}>;`, "");
  }
  const components = definitions.filter((d) => d.kind === "component").map((d) => nodeType(d.code));
  const contentTypes = definitions.filter((d) => d.kind === "content_type").map((d) => nodeType(d.code));
  lines.push(`/** Any component that can appear inside a blocks field. */`);
  lines.push(`export type BuilderComponentNode = ${components.join(" | ") || "never"};`);
  lines.push(`/** The root of a page, by content type. */`);
  lines.push(`export type BuilderContentTypeNode = ${contentTypes.join(" | ") || "never"};`);
  lines.push(`export type BuilderComponentCode = BuilderComponentNode["component"];`);
  lines.push(`export type BuilderContentTypeCode = BuilderContentTypeNode["component"];`, "");
  for (const kind of ["product", "category"] as const) {
    const codes = definitions.filter((d) => d.kind === "component" && d.templateFor === kind).map((d) => quote(d.code));
    lines.push(`/** Components that show ${kind} data: they render inside ${kind} templates and a ${kind}'s own sections, with the ${kind}. */`);
    lines.push(`export type Builder${pascal(kind)}ComponentCode = ${codes.join(" | ") || "never"};`);
  }
  lines.push("");
  return lines.join("\n");
};
